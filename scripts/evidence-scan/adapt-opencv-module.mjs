// Deterministic build adapter. Normalize only blank lines/EOF, not executable code.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const directory = resolve(process.argv[2] ?? 'frontend/public/vendor/opencv/4.13.0-csp1');
const raw = readFileSync(resolve(directory, 'opencv.js'), 'utf8');
const input = raw.replace(/^[ \t]+$/gm, '').trimEnd() + '\n';
const marker = '}(this, function () {';
if (input.split(marker).length !== 2 || /\bnew\s+Function\b|\beval\s*\(/.test(input)) throw new Error('OpenCV wrapper changed; review before adapting.');
const moduleSource = '// OpenCV 4.13.0, Apache-2.0. See LICENSE-OpenCV.txt. Generated by adapt-opencv-module.mjs.\n'
  + 'var Module = {locateFile: name => new URL(name, import.meta.url).href};\n'
  + input.replace(marker, '}(globalThis, function () {') + '\nexport default globalThis.cv;\n';
writeFileSync(resolve(directory, 'opencv-module.js'), moduleSource);
writeFileSync(resolve(directory, 'opencv.js'), input);
const names = ['opencv.js', 'opencv_js.wasm', 'opencv-module.js'];
const files = Object.fromEntries(names.map(name => {
  const content = readFileSync(resolve(directory, name));
  return [name, { bytes: content.length, sha256: createHash('sha256').update(content).digest('hex') }];
}));
writeFileSync(resolve(directory, 'SHA256SUMS'), names.map(name => `${files[name].sha256}  ${name}\n`).join(''));
const manifestPath = resolve(directory, 'manifest.json');
if (existsSync(manifestPath)) {
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  manifest.packaging_normalization = 'blank whitespace-only lines and single final LF';
  manifest.files = files;
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
}
const digest = createHash('sha256').update(moduleSource).digest('hex');
console.log(JSON.stringify({ name: 'opencv-module.js', bytes: Buffer.byteLength(moduleSource), sha256: digest }));
